package subtitles

// langProfile weighs decoded characters by how plausible they are in the
// language a legacy charset is normally used for. The common sets are short
// frequency lists: in real dialogue a few hundred characters cover most of
// the text, while a wrong decoding scatters over the whole repertoire.
type langProfile struct {
	common    map[rune]struct{}
	second    map[rune]struct{}
	secondW   float64
	hanW      float64
	kanaW     float64
	halfKanaW float64
	hangulW   float64
	jamoW     float64
}

func (p *langProfile) weight(r rune) float64 {
	if _, ok := p.common[r]; ok {
		return 1
	}
	if _, ok := p.second[r]; ok {
		return p.secondW
	}
	switch {
	case r >= 0x3041 && r <= 0x30ff:
		return p.kanaW
	case r >= 0xff61 && r <= 0xff9f:
		return p.halfKanaW
	case r >= 0xac00 && r <= 0xd7a3:
		return p.hangulW
	case r >= 0x3131 && r <= 0x318e:
		return p.jamoW
	case r >= 0x4e00 && r <= 0x9fff, r >= 0x3400 && r <= 0x4dbf, r >= 0xf900 && r <= 0xfaff, r >= 0x20000 && r <= 0x3134f:
		return p.hanW
	case r >= 0x3000 && r <= 0x303f, r >= 0xff01 && r <= 0xff60, r >= 0xffe0 && r <= 0xffee:
		return 0.8
	case r >= 0x2010 && r <= 0x206f:
		return 0.6
	case r >= 0x1f300 && r <= 0x1faff, r >= 0x2600 && r <= 0x27bf:
		return 0.5
	case r >= 0x2460 && r <= 0x25ff:
		return 0.2
	}
	return 0.05
}

func runeSet(lists ...string) map[rune]struct{} {
	set := map[rune]struct{}{}
	for _, list := range lists {
		for _, r := range list {
			set[r] = struct{}{}
		}
	}
	return set
}

