func TestNFOWritePreparationLibraryByteCapacity(t *testing.T) {
	f, service, _, request := nfoWritePreparationFixture(t)
	first, _, err := service.Prepare(f.ctx, f.a, "byte-base", request)
	if err != nil {
		t.Fatal("prepare byte fixture")
	}
	// Generate large bytes inside PostgreSQL, without printing or returning them.
	// One row has two exact 32MiB documents. The second exceeds the 128MiB library
	// cap once recipes and the existing small row are included.
	query := `WITH large AS MATERIALIZED (SELECT convert_to(rpad('<movie/>',33554432,' '),'UTF8') AS value), recipe AS MATERIALIZED (SELECT p.*,convert_to((convert_from(request_bytes,'UTF8')::jsonb||jsonb_build_object('maxBytes',33554432))::text,'UTF8') AS encoded FROM nfo_write_preparations p WHERE id=$1::uuid)
 INSERT INTO nfo_write_preparations(id,actor_id,idempotency_key,version,request_bytes,request_digest,library_id,item_id,source_id,root_id,kind,revision,generation,root_generation,root_path,relative_path,media_path,directory_path,max_bytes,modified_unix_nano,original_bytes,original_sha256,replacement_bytes,replacement_sha256,native_receipt)
 SELECT gen_random_uuid(),actor_id,$2,version,encoded,encode(sha256(encoded),'hex'),library_id,item_id,source_id,root_id,kind,revision,generation,root_generation,root_path,relative_path,media_path,directory_path,33554432,modified_unix_nano,value,encode(sha256(value),'hex'),value,encode(sha256(value),'hex'),native_receipt FROM recipe CROSS JOIN large`
	if _, err := f.s.Pool.Exec(f.ctx, query, first.ID, "large-one"); err != nil {
		t.Fatal("byte quota rejected below limit")
	}
	_, err = f.s.Pool.Exec(f.ctx, query, first.ID, "large-two")
	jobMetricMigrationRejected(t, err)
	var rows int
	if err := f.s.Pool.QueryRow(f.ctx, `SELECT count(*) FROM nfo_write_preparations`).Scan(&rows); err != nil || rows != 2 {
		t.Fatal("byte capacity failure changed stored rows")
	}
}

func TestNFOWritePreparationMigrationEmptyRoundTripAndRetainedRefusal(t *testing.T) {
	t.Run("empty", func(t *testing.T) {
		f := newJobFixture(t)
		jobMetricMigration(t, f, "down", 46)
		jobMetricMigration(t, f, "down", 45)
		jobMetricMigration(t, f, "up", SchemaVersion)
		if err := f.s.Ready(f.ctx); err != nil {
			t.Fatal("new schema not ready")
		}
	})
	t.Run("retained", func(t *testing.T) {
		f, _, _, request := nfoWritePreparationFixture(t)
		prepared := legacyNFOWritePreparationFixture(t, f, request, "retained", 46)
		if _, _, err := Migrate(f.ctx, f.s.Pool.Config().ConnString(), "down"); err == nil {
			t.Fatal("downgrade discarded prepared output")
		}
		version, dirty, err := Migrate(f.ctx, f.s.Pool.Config().ConnString(), "status")
		if err != nil || version != 45 || !dirty {
			t.Fatal("refused downgrade lost dirty state")
		}
		digest, _ := domain.NFOWriteRequestDigest(request)
		retained, err := f.s.FindNFOWritePreparation(f.ctx, f.a, "retained", digest)
		if err != nil || retained.ID != prepared.ID || !bytes.Equal(retained.Replacement, prepared.Replacement) {
			t.Fatal("refused downgrade changed output")
		}
		if err := f.s.Ready(f.ctx); err == nil {
			t.Fatal("dirty schema accepted")
		}
	})
}
