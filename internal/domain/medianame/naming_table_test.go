func TestParsePathNamingTable(t *testing.T) {
	if len(namingCases) < 200 {
		t.Fatalf("G21.4 requires at least 200 naming cases, have %d", len(namingCases))
	}
	seen := map[string]bool{}
	for _, tc := range namingCases {
		key := tc.path
		if tc.dates {
			key = "dates:" + key
		}
		if seen[key] {
			t.Fatalf("duplicate case %q", key)
		}
		seen[key] = true
		t.Run(key, func(t *testing.T) {
			if got := describe(ParsePath(tc.path, Options{DateEpisodes: tc.dates})); got != tc.want {
				t.Fatalf("ParsePath(%q)\n got: %s\nwant: %s", tc.path, got, tc.want)
			}
		})
	}
}
